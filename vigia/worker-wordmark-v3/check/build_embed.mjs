// Build-time (offline) step: trims the extracted glyph JSON to the exact subset the Worker needs and writes fontdata.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
const G = "/tmp/claude-0/-home-user-vnext/2925f9ec-a7f0-5d7b-8625-89ea269969dd/scratchpad/logo/fonts/glyphs/";
const LET = [..."ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"], SYM = [..."&.-'"];
const ACC = [..."ÁÀÂÃÉÈÊÍÌÎÓÒÔÕÚÙÛÜÇ"].filter(Boolean);
const spec = {
  serif: ["corminf600", [...LET, ...SYM, ...ACC], true],   // brand name (Cormorant Infant SemiBold, OFL)
  ital: ["cormgar400i", [...LET], false],                  // monogram initials only (Cormorant Garamond Italic, OFL)
  sans: ["jost500", [...LET, ...SYM, ...ACC], true],       // descriptors / tracked sans (Jost Medium, OFL)
  didone: ["bodoni500", [...LET], false],                  // reserve design D: giant initial (Bodoni Moda Medium, OFL)
};
const out = {}; const sizes = {};
for (const [k, [file, chars, keepKern]] of Object.entries(spec)) {
  const j = JSON.parse(readFileSync(G + file + ".json", "utf8")), o = { cap: j.cap, sp: j.sp, adv: {}, p: {}, comp: {}, marks: {}, kern: {} };
  const need = new Set(chars); const usedMarks = new Set();
  for (const ch of chars) {
    if (j.adv[ch] != null) o.adv[ch] = j.adv[ch];
    if (j.p[ch]) o.p[ch] = j.p[ch];
    if (j.comp[ch]) { o.comp[ch] = j.comp[ch]; for (const [n] of j.comp[ch]) if (n[0] === "@") usedMarks.add(n.slice(1)); }
  }
  for (const m of usedMarks) o.marks[m] = j.marks[m];
  // composites reference base glyphs: make sure they are present
  for (const ch of Object.keys(o.comp)) for (const [n] of o.comp[ch]) if (n[0] !== "@" && !o.p[n]) { o.p[n] = j.p[n]; o.adv[n] = j.adv[n]; }
  if (keepKern) for (const [pair, v] of Object.entries(j.kern)) if (need.has(pair[0]) && need.has(pair[1]) && LET.includes(pair[0]) && LET.includes(pair[1]) || (SYM.includes(pair[0]) || SYM.includes(pair[1])) && need.has(pair[0]) && need.has(pair[1])) o.kern[pair] = v;
  for (const e of ["comp", "marks", "kern"]) if (!Object.keys(o[e]).length) delete o[e];
  out[k] = o; const raw = JSON.stringify(o); sizes[k] = { glyphs: Object.keys(o.adv).length, raw: raw.length, gzip: gzipSync(raw, { level: 9 }).length };
}
const js = "// GENERATED by build_embed.mjs - glyph outlines (1000 upm, relative path commands) of OFL fonts: Cormorant Infant, Cormorant Garamond, Jost, Bodoni Moda\nexport const FONTS = " + JSON.stringify(out) + ";\n";
writeFileSync(new URL("./fontdata.mjs", import.meta.url), js);
const tot = { raw: js.length, gzip: gzipSync(js, { level: 9 }).length };
console.log(JSON.stringify(sizes), "TOTAL", tot, "base64(gzip)=", Math.ceil(tot.gzip * 4 / 3));
